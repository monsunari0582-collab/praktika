from database.connection import get_connection


def compress_schedule(conn):
    cursor = conn.cursor()

    cursor.execute("SELECT ид FROM КЛАСС")
    классы = [row["ид"] for row in cursor.fetchall()]

    for класс_ид in классы:
        for день in range(1, 7):
            cursor.execute("""
                SELECT ид, номер_урока FROM УРОК
                WHERE класс_ид = ? AND день_недели = ?
                ORDER BY номер_урока
            """, (класс_ид, день))
            уроки = cursor.fetchall()

            for новый_номер, урок in enumerate(уроки, start=1):
                if урок["номер_урока"] != новый_номер:
                    cursor.execute("""
                        UPDATE УРОК SET номер_урока = ?
                        WHERE ид = ?
                    """, (новый_номер, урок["ид"]))

    conn.commit()


def generate_schedule():
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("DELETE FROM УРОК")
    conn.commit()

    cursor.execute("SELECT ид, параллель, буква FROM КЛАСС")
    классы = cursor.fetchall()
    
    # Фильтруем классы 2-4 параллелей с обязательной субботой
    классы_с_суббота = [к for к in классы if к["параллель"] in ("2", "3", "4")]

    cursor.execute("SELECT учитель_ид, предмет_ид FROM УЧИТЕЛЬ_ПРЕДМЕТ")
    учитель_предмет = cursor.fetchall()

    предмет_учителя = {}
    for row in учитель_предмет:
        пид = row["предмет_ид"]
        уид = row["учитель_ид"]
        if пид not in предмет_учителя:
            предмет_учителя[пид] = []
        предмет_учителя[пид].append(уид)

    cursor.execute("""
        SELECT ид_сущности, значение FROM ОГРАНИЧЕНИЕ
        WHERE тип_сущности = 'учитель' AND тип_правила = 'нерабочий_день'
    """)
    нерабочие_дни = {}
    for row in cursor.fetchall():
        уид = row["ид_сущности"]
        день = int(row["значение"])
        if уид not in нерабочие_дни:
            нерабочие_дни[уид] = set()
        нерабочие_дни[уид].add(день)

    cursor.execute("SELECT учитель_ид, класс_ид FROM УЧИТЕЛЬ_КЛАСС")
    учитель_классы = {}
    for row in cursor.fetchall():
        уид = row["учитель_ид"]
        кид = row["класс_ид"]
        if уид not in учитель_классы:
            учитель_классы[уид] = set()
        учитель_классы[уид].add(кид)

    # Загружаем учебный план для всех классов
    учебный_план_классов = {}
    все_часов = {}
    предмет_часы = {}  # Словарь для хранения часов каждого предмета (усредняя по классам)
    
    for класс in классы:
        класс_ид = класс["ид"]
        cursor.execute("""
            SELECT предмет_ид, часов_в_неделю
            FROM УЧЕБНЫЙ_ПЛАН WHERE класс_ид = ?
        """, (класс_ид,))
        план = cursor.fetchall()
        учебный_план_классов[класс_ид] = {
            row["предмет_ид"]: row["часов_в_неделю"] for row in план
        }
        все_часов[класс_ид] = sum(row["часов_в_неделю"] for row in план)
        
        # Собираем часы для каждого предмета
        for row in план:
            пид = row["предмет_ид"]
            часов = row["часов_в_неделю"]
            if пид not in предмет_часы:
                предмет_часы[пид] = []
            предмет_часы[пид].append(часов)

    # Функция для определения приоритета по часам
    def приоритет_по_часам(предмет_ид):
        if предмет_ид not in предмет_часы or not предмет_часы[предмет_ид]:
            return 3  # Среднее значение по умолчанию
        
        # Берём среднее количество часов по всем классам
        средние_часы = sum(предмет_часы[предмет_ид]) / len(предмет_часы[предмет_ид])
        
        if средние_часы >= 5:
            return 1  # Очень важный предмет (русский, математика)
        elif средние_часы >= 3:
            return 2  # Важный предмет (английский, история, физика)
        elif средние_часы >= 2:
            return 3  # Средне важный
        else:
            return 4  # Менее важный (1 час в неделю)



    уроки_добавлены = 0
    уроки_пропущены = 0

    # === ЭТАП 1: Расставляем обязательные 2 урока по субботам ===
    занятые_классы = {}
    занятые_учителя = {}
    часов_учителя = {}
    поставлено_часов = {}
    предмет_в_день = {}
    уроков_в_день_класса = {}  # (класс_ид, день) -> количество уроков
    последний_урок = {}  # (класс_ид, день) -> (предмет_ид, учитель_ид, номер_урока)
    
    # Сначала расставляем предметы для классов с обязательной субботой
    for класс in классы_с_суббота:
        класс_ид = класс["ид"]
        план = учебный_план_классов.get(класс_ид, {})
        
        # Пытаемся поставить 2 урока в субботу (день=6, уроки 1-2)
        уроков_в_субботу = 0
        for урок in [1, 2]:
            if уроков_в_субботу >= 2:
                break
            
            # Выбираем предмет для субботы
            для_субботы = []
            for предмет_ид, нужно_часов in план.items():
                уже_поставлено = поставлено_часов.get((класс_ид, предмет_ид), 0)
                остаток = нужно_часов - уже_поставлено
                if остаток > 0:
                    уже_в_субботу = 1 if предмет_в_день.get((класс_ид, предмет_ид, 6)) else 0
                    приор = приоритет_по_часам(предмет_ид)
                    для_субботы.append((уже_в_субботу, приор, остаток, предмет_ид))
            
            для_субботы.sort(key=lambda x: (x[0], x[1], -x[2]))
            
            поставлен = False
            for _, __, ___, предмет_ид in для_субботы:
                if предмет_ид not in предмет_учителя:
                    continue
                
                учитель_ид = None
                for уид in предмет_учителя[предмет_ид]:
                    if 6 in нерабочие_дни.get(уид, set()):  # 6 - суббота
                        continue
                    if уид in учитель_классы and класс_ид not in учитель_классы[уид]:
                        continue
                    if уид not in занятые_учителя.get((6, урок), set()):
                        # Проверяем: если предмет уже в субботу, разрешаем только если это же урок был в предыдущем номере с тем же учителем
                        если_есть_в_день = предмет_в_день.get((класс_ид, предмет_ид, 6))
                        если_был_подряд = последний_урок.get((класс_ид, 6)) == (предмет_ид, уид, урок - 1)
                        
                        if если_есть_в_день and not если_был_подряд:
                            continue
                        
                        учитель_ид = уид
                        break
                
                if учитель_ид is None:
                    continue
                
                cursor.execute("""
                    INSERT INTO УРОК
                    (класс_ид, предмет_ид, учитель_ид, день_недели, номер_урока, статус)
                    VALUES (?, ?, ?, ?, ?, 'черновик')
                """, (класс_ид, предмет_ид, учитель_ид, 6, урок))
                
                занятые_учителя.setdefault((6, урок), set()).add(учитель_ид)
                занятые_классы[(класс_ид, 6, урок)] = True
                предмет_в_день[(класс_ид, предмет_ид, 6)] = True
                часов_учителя[учитель_ид] = часов_учителя.get(учитель_ид, 0) + 1
                поставлено_часов[(класс_ид, предмет_ид)] = поставлено_часов.get((класс_ид, предмет_ид), 0) + 1
                уроков_в_день_класса[(класс_ид, 6)] = уроков_в_день_класса.get((класс_ид, 6), 0) + 1
                последний_урок[(класс_ид, 6)] = (предмет_ид, учитель_ид, урок)
                
                уроки_добавлены += 1
                уроков_в_субботу += 1
                поставлен = True
                break

    # === ЭТАП 2: Продолжаем обычное расписание ===
    # Слоты: сначала пн-пт 1-6 урок, потом суббота 1-7, потом пн-сб 7-й урок
    слоты = (
        [(день, урок) for урок in range(1, 7) for день in range(1, 6)] +
        [(6, урок) for урок in range(1, 8)] +
        [(день, 7) for день in range(1, 7)]
    )

    for день, урок in слоты:
        for класс in классы:
            класс_ид = класс["ид"]

            if занятые_классы.get((класс_ид, день, урок)):
                continue
            
            # Для 1-4 классов максимум 5 уроков в день
            if класс["параллель"] in ("1", "2", "3", "4"):
                уроков_в_день = уроков_в_день_класса.get((класс_ид, день), 0)
                if уроков_в_день >= 5:
                    continue

            # 7-й урок только если нужен
            if урок == 7 and все_часов.get(класс_ид, 0) <= 36:
                continue
            
            # Пропускаем уроки №1 и №2 в субботу для классов 2-4 параллелей (уже расставили)
            if день == 6 and класс["параллель"] in ("2", "3", "4") and урок <= 2:
                continue

            план = учебный_план_классов.get(класс_ид, {})

            # Выбираем предмет — сначала те у которых учитель наиболее загружен
            # Сначала предметы которых ещё нет в этот день, потом повторы
            предметы_с_остатком = []
            for предмет_ид, нужно_часов in план.items():
                уже_поставлено = поставлено_часов.get((класс_ид, предмет_ид), 0)
                остаток = нужно_часов - уже_поставлено
                if остаток > 0:
                    загруженность = 0
                    if предмет_ид in предмет_учителя:
                        for уид in предмет_учителя[предмет_ид]:
                            загруженность = max(загруженность, часов_учителя.get(уид, 0))
                    уже_в_день = 1 if предмет_в_день.get((класс_ид, предмет_ид, день)) else 0
                    приор = приоритет_по_часам(предмет_ид)
                    # В субботу лёгкие предметы идут первыми
                    if день == 6:
                        приор = 5 - приор
                    предметы_с_остатком.append((уже_в_день, приор, загруженность, остаток, предмет_ид))

            # Сортируем: сначала новые в день, потом важные предметы, потом загруженность
            предметы_с_остатком.sort(key=lambda x: (x[0], x[1], -x[2], -x[3]))

            поставлен = False
            for _, __, ___, ____, предмет_ид in предметы_с_остатком:
                if предмет_ид not in предмет_учителя:
                    continue

                учитель_ид = None
                for уид in предмет_учителя[предмет_ид]:
                    if день in нерабочие_дни.get(уид, set()):
                        continue
                    if уид in учитель_классы and класс_ид not in учитель_классы[уид]:
                        continue
                    if уид not in занятые_учителя.get((день, урок), set()):
                        # Проверяем: если предмет уже в день, разрешаем только если это же урок был в предыдущем номере с тем же учителем
                        если_есть_в_день = предмет_в_день.get((класс_ид, предмет_ид, день))
                        если_был_подряд = последний_урок.get((класс_ид, день)) == (предмет_ид, уид, урок - 1)
                        
                        if если_есть_в_день and not если_был_подряд:
                            # Предмет уже есть в день и не был подряд - пропускаем
                            continue
                        
                        учитель_ид = уид
                        break

                if учитель_ид is None:
                    continue

                cursor.execute("""
                    INSERT INTO УРОК
                    (класс_ид, предмет_ид, учитель_ид, день_недели, номер_урока, статус)
                    VALUES (?, ?, ?, ?, ?, 'черновик')
                """, (класс_ид, предмет_ид, учитель_ид, день, урок))

                занятые_учителя.setdefault((день, урок), set()).add(учитель_ид)
                занятые_классы[(класс_ид, день, урок)] = True
                предмет_в_день[(класс_ид, предмет_ид, день)] = True
                часов_учителя[учитель_ид] = часов_учителя.get(учитель_ид, 0) + 1
                поставлено_часов[(класс_ид, предмет_ид)] = поставлено_часов.get((класс_ид, предмет_ид), 0) + 1
                уроков_в_день_класса[(класс_ид, день)] = уроков_в_день_класса.get((класс_ид, день), 0) + 1
                последний_урок[(класс_ид, день)] = (предмет_ид, учитель_ид, урок)

                уроки_добавлены += 1
                поставлен = True
                break

    # Считаем пропущенные
    пропущенные_список = []
    for класс in классы:
        класс_ид = класс["ид"]
        название_класса = f"{класс['параллель']}{класс['буква']}"
        for предмет_ид, нужно_часов in учебный_план_классов.get(класс_ид, {}).items():
            уже_поставлено = поставлено_часов.get((класс_ид, предмет_ид), 0)
            остаток = нужно_часов - уже_поставлено
            if остаток > 0:
                cursor.execute("SELECT название FROM ПРЕДМЕТ WHERE ид = ?", (предмет_ид,))
                предмет = cursor.fetchone()
                название_предмета = предмет["название"] if предмет else str(предмет_ид)
                пропущенные_список.append(f"{название_класса}: {название_предмета} ({остаток} ч.)")
                уроки_пропущены += остаток

    conn.commit()
    compress_schedule(conn)
    conn.close()

    return уроки_добавлены, уроки_пропущены, пропущенные_список


def generate_schedule_no_teachers():
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("DELETE FROM УРОК")
    conn.commit()

    cursor.execute("SELECT ид FROM КЛАСС")
    классы = cursor.fetchall()

    # сначала все 6 дней 1-6 урок, потом все 6 дней 7-й урок
    слоты = (
        [(день, урок) for день in range(1, 7) for урок in range(1, 7)] +
        [(день, 7) for день in range(1, 7)]
    )

    занятые_классы = {}
    предмет_в_день = {}

    уроки_добавлены = 0
    уроки_пропущены = 0

    for класс in классы:
        класс_ид = класс["ид"]

        cursor.execute("""
            SELECT предмет_ид, часов_в_неделю
            FROM УЧЕБНЫЙ_ПЛАН WHERE класс_ид = ?
        """, (класс_ид,))
        учебный_план = cursor.fetchall()

        всего_часов = sum(п["часов_в_неделю"] for п in учебный_план)
        использовать_7_урок = всего_часов > 36

        текущие_слоты = слоты if использовать_7_урок else [
            (день, урок) for день, урок in слоты if урок <= 6
        ]

        for план in учебный_план:
            предмет_ид = план["предмет_ид"]
            часов = план["часов_в_неделю"]
            поставлено = 0

            for день, урок in текущие_слоты:
                if поставлено >= часов:
                    break

                if занятые_классы.get((класс_ид, день, урок)):
                    continue

                if предмет_в_день.get((класс_ид, предмет_ид, день)):
                    continue

                cursor.execute("""
                    INSERT INTO УРОК
                    (класс_ид, предмет_ид, учитель_ид, день_недели, номер_урока, статус)
                    VALUES (?, ?, NULL, ?, ?, 'черновик')
                """, (класс_ид, предмет_ид, день, урок))

                занятые_классы[(класс_ид, день, урок)] = True
                предмет_в_день[(класс_ид, предмет_ид, день)] = True

                поставлено += 1
                уроки_добавлены += 1

            уроки_пропущены += часов - поставлено

    conn.commit()
    compress_schedule(conn)
    conn.close()

    return уроки_добавлены, уроки_пропущены