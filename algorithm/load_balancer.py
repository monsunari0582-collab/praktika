"""Автоматическое распределение классов между учителями.

У учителя задаются только предметы и ступени, в которых он работает (1–4, 5–9, 10–11).
Часы не вводятся: программа сама раскладывает классы так, чтобы нагрузка учителей
была как можно ровнее, и потом показывает, кто сколько работает.

Предметы, которые на одной ступени ведут одни и те же учителя, объединяются в группу
(например, «Математика, Алгебра, Геометрия, Вероятность и статистика» в 5–9).
Внутри группы все предметы одного класса ведёт один учитель — это «блок».
"""
from collections import defaultdict

from algorithm.scheduler import ступень_по_параллели

СТУПЕНИ = ("1-4", "5-9", "10-11")
КОЛОНКА_СТУПЕНИ = {"1-4": "работает_1_4", "5-9": "работает_5_9", "10-11": "работает_10_11"}

ВЕС_ИЗМЕНЕНИЯ = 0.001   # при равной нагрузке оставляем как было
ЛИМИТ_ПЕРЕБОРА = 300_000


def load_data(cursor):
    cursor.execute("SELECT ид, параллель, буква FROM КЛАСС ORDER BY CAST(параллель AS INTEGER), буква")
    классы = cursor.fetchall()

    cursor.execute("SELECT ид, название FROM ПРЕДМЕТ")
    предметы = {row["ид"]: " ".join(row["название"].split()) for row in cursor.fetchall()}

    cursor.execute("SELECT ид, фио, работает_1_4, работает_5_9, работает_10_11 FROM УЧИТЕЛЬ")
    учителя = {
        row["ид"]: {
            "фио": row["фио"],
            "ступени": {с for с in СТУПЕНИ if row[КОЛОНКА_СТУПЕНИ[с]]},
        }
        for row in cursor.fetchall()
    }

    cursor.execute("SELECT учитель_ид, предмет_ид FROM УЧИТЕЛЬ_ПРЕДМЕТ")
    предметы_учителя = defaultdict(set)
    for row in cursor.fetchall():
        if row["учитель_ид"] in учителя:
            предметы_учителя[row["учитель_ид"]].add(row["предмет_ид"])

    cursor.execute("SELECT класс_ид, предмет_ид, часов_в_неделю FROM УЧЕБНЫЙ_ПЛАН")
    план = {(row["класс_ид"], row["предмет_ид"]): row["часов_в_неделю"] for row in cursor.fetchall()}

    cursor.execute("SELECT учитель_ид, предмет_ид, класс_ид, часов FROM УЧИТЕЛЬ_ПРЕДМЕТ_КЛАСС")
    назначения = {(row["класс_ид"], row["предмет_ид"]): (row["учитель_ид"], row["часов"]) for row in cursor.fetchall()}

    return {
        "классы": [
            {"ид": к["ид"], "название": f"{к['параллель']}{к['буква']}",
             "ступень": ступень_по_параллели(к["параллель"])}
            for к in классы
        ],
        "предметы": предметы,
        "учителя": учителя,
        "предметы_учителя": предметы_учителя,
        "план": план,
        "назначения": назначения,
    }


def find_groups(data):
    """Группы «ступень + предметы + учителя» — связные компоненты графа учитель—предмет."""
    группы = []
    for ступень in СТУПЕНИ:
        классы_ступени = [к for к in data["классы"] if к["ступень"] == ступень]
        ид_классов = {к["ид"] for к in классы_ступени}
        предметы_ступени = {п for (к, п) in data["план"] if к in ид_классов}
        if not предметы_ступени:
            continue

        родитель = {}

        def найти(x):
            while родитель.setdefault(x, x) != x:
                родитель[x] = родитель[родитель[x]]
                x = родитель[x]
            return x

        for п in предметы_ступени:
            найти(("п", п))
        for у_ид, предметы_у in data["предметы_учителя"].items():
            if ступень not in data["учителя"][у_ид]["ступени"]:
                continue
            for п in предметы_у & предметы_ступени:
                родитель[найти(("у", у_ид))] = найти(("п", п))

        компоненты = defaultdict(lambda: {"предметы": set(), "учителя": set()})
        for узел in list(родитель):
            вид, ид = узел
            компоненты[найти(узел)]["предметы" if вид == "п" else "учителя"].add(ид)

        for к in компоненты.values():
            if not к["предметы"]:
                continue
            группы.append({
                "ступень": ступень,
                "предметы": к["предметы"],
                "учителя": sorted(к["учителя"], key=lambda у: data["учителя"][у]["фио"]),
                "классы": классы_ступени,
            })

    группы.sort(key=lambda г: (СТУПЕНИ.index(г["ступень"]), -len(г["учителя"]),
                               sorted(data["предметы"][п] for п in г["предметы"])))
    return группы


def _части_класса(data, группа, предметы):
    """Делит предметы класса на части, каждую из которых ведёт один учитель.

    Вместе остаются предметы, которые могут вести одни и те же учителя
    (или одни — подмножество других): русский с литературой — да, а русский
    с иностранным, если их ведут разные люди, — нет.
    """
    учителя_предмета = {
        п: frozenset(у for у in группа["учителя"] if п in data["предметы_учителя"][у])
        for п in предметы
    }
    части = []  # [(учителя, [предметы])]
    for п in sorted(предметы, key=lambda п: (-len(учителя_предмета[п]), data["предметы"][п])):
        своё = учителя_предмета[п]
        for i, (учителя, список) in enumerate(части):
            if своё and (своё <= учителя or учителя <= своё):
                части[i] = (учителя & своё, список + [п])
                break
        else:
            части.append((своё, [п]))
    return [sorted(список, key=lambda п: data["предметы"][п]) for _, список in части]


def build_blocks(data, группа):
    """Блоки «класс + предметы», которые ведёт один учитель."""
    блоки = []
    for класс in группа["классы"]:
        предметы = [п for п in группа["предметы"] if (класс["ид"], п) in data["план"]]
        if not предметы:
            continue

        def подходящие(нужные):
            return [у for у in группа["учителя"] if set(нужные) <= data["предметы_учителя"][у]]

        for часть in _части_класса(data, группа, предметы):
            текущие = {data["назначения"].get((класс["ид"], п), (None,))[0] for п in часть}
            блоки.append({
                "класс": класс,
                "предметы": [(п, data["план"][(класс["ид"], п)]) for п in часть],
                "часов": sum(data["план"][(класс["ид"], п)] for п in часть),
                "подходящие": подходящие(часть),
                # None — не назначен, "разные" — у предметов блока разные учителя
                "текущий": текущие.pop() if len(текущие) == 1 else "разные",
            })
    return блоки


def total_loads(data):
    """Сколько часов каждый учитель ведёт по распределению: {учитель: {ступень: часов}}."""
    ступень_класса = {к["ид"]: к["ступень"] for к in data["классы"]}
    нагрузка = defaultdict(lambda: defaultdict(int))
    for (класс_ид, _), (учитель_ид, часов) in data["назначения"].items():
        нагрузка[учитель_ид][ступень_класса.get(класс_ид)] += часов or 0
    return нагрузка


def loads_after(data, блоки, учителя_блоков):
    """Общая нагрузка учителей {учитель: часов}, если блоки получат указанных учителей."""
    нагрузка = defaultdict(int)
    for учитель_ид, по_ступеням in total_loads(data).items():
        нагрузка[учитель_ид] = sum(по_ступеням.values())
    for блок, учитель_ид in zip(блоки, учителя_блоков):
        if учитель_ид is None:
            continue
        for п, часов in блок["предметы"]:
            назн = data["назначения"].get((блок["класс"]["ид"], п))
            if назн:
                нагрузка[назн[0]] -= назн[1] or 0
            нагрузка[учитель_ид] += часов
    return нагрузка


def propose(data, группа, блоки):
    """Подбирает учителя для каждого блока так, чтобы общая нагрузка учителей была ровнее.

    Учитываются и часы учителя вне группы (например, на другой ступени).
    Возвращает список учителей по индексам блоков (None — некого назначить).
    """
    порядок = sorted(
        (i for i, б in enumerate(блоки) if б["подходящие"]),
        key=lambda i: (-блоки[i]["часов"], len(блоки[i]["подходящие"]))
    )

    # Нагрузка учителей без блоков группы — её подбор не меняет
    нагрузка = loads_after(data, [], [])
    for б in блоки:
        for п, _ in б["предметы"]:
            назн = data["назначения"].get((б["класс"]["ид"], п))
            if назн:
                нагрузка[назн[0]] -= назн[1] or 0

    def стоимость(изменений):
        # Сумма квадратов меньше, когда часы распределены ровнее.
        # При добавлении часов она только растёт, поэтому годится и как нижняя граница
        return sum(нагрузка[у] ** 2 for у in группа["учителя"]) + изменений * ВЕС_ИЗМЕНЕНИЯ

    # Жадное начальное решение: блок — самому свободному из подходящих
    лучшее = [None] * len(блоки)
    изменений = 0
    for i in порядок:
        б = блоки[i]
        у = min(б["подходящие"], key=lambda у: (нагрузка[у], у != б["текущий"]))
        лучшее[i] = у
        нагрузка[у] += б["часов"]
        изменений += у != б["текущий"]
    лучшая_стоимость = стоимость(изменений)
    for i in порядок:
        нагрузка[лучшее[i]] -= блоки[i]["часов"]

    # Перебор с отсечением
    текущее = [None] * len(блоки)
    узлов = 0

    def перебор(k, изменений):
        nonlocal лучшая_стоимость, лучшее, узлов
        узлов += 1
        if узлов > ЛИМИТ_ПЕРЕБОРА or стоимость(изменений) >= лучшая_стоимость:
            return
        if k == len(порядок):
            лучшая_стоимость = стоимость(изменений)
            лучшее = list(текущее)
            return
        i = порядок[k]
        б = блоки[i]
        # Сначала текущий учитель — быстрее находит хорошие решения
        for у in sorted(б["подходящие"], key=lambda у: у != б["текущий"]):
            текущее[i] = у
            нагрузка[у] += б["часов"]
            перебор(k + 1, изменений + (у != б["текущий"]))
            нагрузка[у] -= б["часов"]
        текущее[i] = None

    перебор(0, 0)
    return лучшее


def propose_all(data):
    """Предложение по всем группам сразу: [(группа, блоки, учителя_блоков)].

    Группы обрабатываются по очереди, и каждая видит нагрузку, предложенную
    предыдущими, — так учитель на двух ступенях не перегружается.
    """
    назначения = dict(data["назначения"])
    рабочие = dict(data, назначения=назначения)
    результат = []
    for группа in find_groups(data):
        блоки = build_blocks(рабочие, группа)
        предложение = propose(рабочие, группа, блоки)
        for блок, у in zip(блоки, предложение):
            if у is not None:
                for п, часов in блок["предметы"]:
                    назначения[(блок["класс"]["ид"], п)] = (у, часов)
        результат.append((группа, блоки, предложение))
    return результат


def apply_assignment(cursor, data, блок, учитель_ид):
    """Закрепляет все предметы блока за учителем (часы — по учебному плану)."""
    # Импорт здесь, чтобы алгоритм не зависел от интерфейса при загрузке
    from ui.teacher_subject_class_tab import _sync_teacher_class

    класс_ид = блок["класс"]["ид"]
    прежние = set()
    for предмет_ид, часов in блок["предметы"]:
        назн = data["назначения"].get((класс_ид, предмет_ид))
        if назн:
            прежние.add(назн[0])
        cursor.execute("""
            INSERT INTO УЧИТЕЛЬ_ПРЕДМЕТ_КЛАСС (учитель_ид, предмет_ид, класс_ид, часов)
            VALUES (?, ?, ?, ?)
            ON CONFLICT(класс_ид, предмет_ид) DO UPDATE SET
                учитель_ид = excluded.учитель_ид, часов = excluded.часов
        """, (учитель_ид, предмет_ид, класс_ид, часов))
    for у in прежние | {учитель_ид}:
        _sync_teacher_class(cursor, у, класс_ид)
